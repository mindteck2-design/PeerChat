const RECENT_STORAGE_KEY = "peerchat_recent_emojis";
const MAX_RECENT_COUNT = 24;

export function getRecentEmojis(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_STORAGE_KEY);
    if (!raw) return DEFAULT_RECENT_EMOJIS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed.filter((x): x is string => typeof x === "string");
    }
  } catch {
    // fallback if parse fails or storage unavailable
  }
  return DEFAULT_RECENT_EMOJIS;
}

export function saveRecentEmoji(emoji: string): string[] {
  try {
    const current = getRecentEmojis();
    const updated = [emoji, ...current.filter((e) => e !== emoji)].slice(
      0,
      MAX_RECENT_COUNT
    );
    localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(updated));
    return updated;
  } catch {
    return [emoji];
  }
}

